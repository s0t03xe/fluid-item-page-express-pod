export function Chevron({ open, size = 20 }: { open: boolean; size?: number }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      className={`shrink-0 transition-transform ${open ? "rotate-180" : ""}`}
    >
      <path
        d="m6 9 6 6 6-6"
        stroke="currentColor"
        strokeWidth="1.8"
        strokeLinecap="round"
        strokeLinejoin="round"
      />
    </svg>
  );
}

export function Collapsible({
  title,
  defaultOpen = false,
  aiLabel = false,
  children,
}: {
  title: string;
  defaultOpen?: boolean;
  aiLabel?: boolean;
  children: ReactNode;
}) {
  const [open, setOpen] = useState(defaultOpen);
  return (
    <section className="px-4 py-4">
      <button
        type="button"
        aria-expanded={open}
        onClick={() => setOpen((o) => !o)}
        className="flex w-full items-center justify-between text-left"
      >
        <h2 className="text-[16px] font-bold leading-6 text-ld-text-default">{title}</h2>
        <Chevron open={open} />
      </button>
      {open && <div className="mt-3">{children}</div>}
      {open && aiLabel && (
        <p className="mt-3 flex items-center justify-end gap-1 text-[12px] leading-4 text-[#74767C]">
          Generated by AI <InfoIcon size={14} />
        </p>
      )}
    </section>
  );
}

