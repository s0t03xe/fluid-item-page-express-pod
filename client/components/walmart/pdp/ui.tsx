export function Stars({ rating, size = 14 }: { rating: number; size?: number }) {
  return (
    <div className="flex gap-px" role="img" aria-label={`${rating} out of 5 stars`}>
      {Array.from({ length: 5 }).map((_, i) => {
        const full = i + 1 <= Math.floor(rating);
        const half = !full && i < rating;
        const id = `pdp-star-${size}-${i}-${String(rating).replace(".", "_")}`;
        return (
          <svg key={i} width={size} height={size} viewBox="0 0 12 12" fill="none">
            {half && (
              <defs>
                <linearGradient id={id}>
                  <stop offset="50%" stopColor="#FFC220" />
                  <stop offset="50%" stopColor="transparent" />
                </linearGradient>
              </defs>
            )}
            <path
              d="M6 0.5 7.5 4l3.5.5-2.7 2.5.7 3.5L6 8.7 2.5 10.5l.7-3.5L.5 4.5 4 4Z"
              fill={full ? "#FFC220" : half ? `url(#${id})` : "none"}
              stroke={full ? "none" : "#FFC220"}
              strokeWidth={0.8}
              strokeLinejoin="round"
            />
          </svg>
        );
      })}
    </div>
  );
}
