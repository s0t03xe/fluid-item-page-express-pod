import type { WalmartItem } from "@/lib/walmart-items";
import type { PdpContent, PdpReview } from "@/lib/pdp-content";
import BottomSheet from "@/components/walmart/BottomSheet";
import { Close } from "@/components/walmart/icons";
import { Collapsible, InfoIcon, SECTION_HEADING, Stars } from "@/components/walmart/pdp/ui";

/** Circular status icon for review pills: green check when positive, grey minus otherwise. */
function PillIcon({ good }: { good: boolean }) {
  return (
    <span
      className={`flex h-4 w-4 shrink-0 items-center justify-center rounded-full text-white ${
        good ? "bg-[#2A8703]" : "bg-[#74767C]"
      }`}
    >
      <svg width="10" height="10" viewBox="0 0 24 24" fill="none" aria-hidden="true">
        {good ? (
          <path d="m5 12.5 4.5 4.5L19 7.5" stroke="currentColor" strokeWidth="3.4" strokeLinecap="round" strokeLinejoin="round" />
        ) : (
          <path d="M6 12h12" stroke="currentColor" strokeWidth="3.4" strokeLinecap="round" />
        )}
      </svg>
    </span>
  );
}

function ReviewCard({ r }: { r: PdpReview }) {
  return (
    <article className="flex flex-col gap-1 border-t border-[#E3E4E5] py-3">
      <Stars rating={r.rating} size={13} />
      {r.title && <h3 className="text-[14px] font-bold leading-5 text-ld-text-default">{r.title}</h3>}
      {r.text && <p className="text-[14px] leading-5 text-ld-text-default">{r.text}</p>}
      <p className="text-[12px] leading-4 text-[#74767C]">
        {r.author ?? "Customer"}
        {r.date ? ` · ${r.date}` : ""}
        {r.verified ? " · Verified purchase" : ""}
      </p>
    </article>
  );
}

export function ReviewsSummary({
  item,
  content,
  onOpenReviews,
}: {
  item: WalmartItem;
  content: PdpContent;
  onOpenReviews: () => void;
}) {
  const s = content.reviewSummary;
  const rating = s.average ?? item.rating;
  const pills = [
    ...s.positive.map((text) => ({ text, good: true })),
    ...s.negative.map((text) => ({ text, good: false })),
  ];

  return (
    <Collapsible
      title="Reviews summary"
      defaultOpen
      headingClassName={SECTION_HEADING}
      right={
        <div className="flex items-center gap-2 text-[14px] leading-5 text-ld-text-default">
          <Stars rating={rating} size={13} />
          <span>({rating.toFixed(1)})</span>
        </div>
      }
    >
      {pills.length > 0 && (
        <div className="flex flex-wrap gap-2">
          {pills.map((p) => (
            <span
              key={`${p.good ? "+" : "-"}${p.text}`}
              className="flex items-center gap-1.5 rounded-full border border-[#D0D2D6] bg-white px-3 py-1.5 text-[14px] font-bold leading-5 text-[#041C3C]"
            >
              <PillIcon good={p.good} />
              {p.text}
            </span>
          ))}
        </div>
      )}

      <div className="mt-4 flex items-center justify-between gap-3">
        <button
          type="button"
          onClick={onOpenReviews}
          className="text-left text-[15px] leading-5 text-ld-text-default underline"
        >
          View all reviews
        </button>
        <span className="flex shrink-0 items-center gap-1 text-[12px] leading-4 text-[#74767C]">
          Generated by AI <InfoIcon size={14} />
        </span>
      </div>
    </Collapsible>
  );
}

export function PdpReviewsSheet({
  open,
  onClose,
  item,
  content,
}: {
  open: boolean;
  onClose: () => void;
  item: WalmartItem;
  content: PdpContent;
}) {
  return (
    <BottomSheet open={open} onClose={onClose} heightClass="h-[92%]">
      <div className="flex items-center justify-between px-4 pt-4">
        <h2 className="text-[18px] font-bold leading-6 text-ld-text-default">Customer reviews</h2>
        <button type="button" aria-label="Close" onClick={onClose}>
          <Close size={20} className="text-[#2E2F32]" />
        </button>
      </div>
      <div className="flex-1 overflow-y-auto px-4 pb-6">
        <div className="mt-3 flex items-center gap-3">
          <span className="text-[32px] font-bold leading-10 text-ld-text-default">{item.rating}</span>
          <div className="flex flex-col gap-0.5">
            <Stars rating={item.rating} size={16} />
            <span className="text-[13px] leading-4 text-[#74767C]">{item.ratingCount} reviews</span>
          </div>
        </div>
        <div className="mt-3">
          {content.reviews.length > 0 ? (
            content.reviews.map((r, i) => <ReviewCard key={i} r={r} />)
          ) : (
            <p className="py-6 text-[14px] leading-5 text-[#74767C]">
              Reviews for this item aren&apos;t available in the prototype.
            </p>
          )}
        </div>
      </div>
    </BottomSheet>
  );
}
